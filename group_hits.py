import argparse
import dbm

class Domain:
  def __init__(self, name, evalue, alistart, aliend, envstart, envend):
    self.name = name
    self.evalue = evalue
    self.alistart = alistart
    self.aliend = aliend
    self.envstart = envstart
    self.envend = envend



def stringToDomlist(domstring): #Converts a comma-separated-string of domains into 
                                #a list of domain objects
  fields = domstring.split(',')
  if domstring == "":
    return []
  if int(len(fields)/6) * 6 != len(fields):  
    print("Bad number of fields " + len(fields) + " found in string "+domstring)
    
  startIndex = 0
  domlist = []
  while startIndex < len(fields):
    dom = Domain(fields[startIndex], float(fields[startIndex+1]), int(fields[startIndex + 2]), int(fields[startIndex + 3]), int(fields[startIndex  +4]), int(fields[startIndex+5]))
    domlist = domlist + [dom]
    startIndex+=6

  return domlist

def domlistToSignature(domlist):
  sig =""
  for dom in domlist:
    if sig != "":
      sig+= "+"
    sig += dom.name

  return sig


parser = argparse.ArgumentParser()
parser.add_argument('annfile', help = "File containing annotations for the database that was searched")
parser.add_argument("domtblfiles", nargs = '*', help="Name of one or more domtblout files generated by a search")
args = parser.parse_args()

sequences = {}  #dictionary that will hold sequences, with signature as key
with dbm.open(args.annfile, 'r') as db:
  for dfile in args.domtblfiles:
    with open(dfile, "r") as df:  #Go through each hit in domtblout, finding domain sig
      for line in df:
        if line[0] != '#':  # real data
          fields = line.split()
          sequence = fields[0]

          dom = ""

          try:
            dom = db[sequence].decode("utf-8")
          except KeyError:
            dom = ""

          domlist = stringToDomlist(dom)
          sig = domlistToSignature(domlist)

          if sig not in sequences:
            sequences[sig] = [[float(fields[6]), line]]
          else:
            sequences[sig] += [[float(fields[6]), line]]

#Create list of signatures, sorted in descending order of number of hits per sig.
sigSizes = []
for sig in sequences.keys():
  sigSizes += [[len(sequences[sig]), sig]]

sigSizes.sort(reverse=True, key = lambda x: x[0])

numHits=0
for sig in sigSizes:
  numHits += sig[0]
  if sig[0] > 1:
    print(str(sig[0]) + " hits with signature " + sig[1])
  else:
    print("One hit with signature "+ sig[1])
  for hit in sequences[sig[1]]:
    print(hit[1])
  print("")

print(str(numHits)+ " hits total")